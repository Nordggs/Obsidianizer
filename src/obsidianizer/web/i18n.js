  window.I18N_LANG = "ru";

  function lookup(lang, key) {
    const table = window.I18N[lang];
    return table ? table[key] : null;
  }

  window.t = function (key, params) {
    let s = lookup(window.I18N_LANG, key);
    if (s == null) s = lookup("ru", key);
    if (s == null) return key;
    if (params) {
      for (const name in params) {
        s = s.split("{" + name + "}").join(String(params[name]));
      }
    }
    return s;
  };

  window.applyI18n = function (root) {
    const scope = root || document;
    scope.querySelectorAll("[data-i18n]").forEach(function (el) {
      el.textContent = window.t(el.getAttribute("data-i18n"));
    });
    scope.querySelectorAll("[data-i18n-title]").forEach(function (el) {
      el.setAttribute("title", window.t(el.getAttribute("data-i18n-title")));
    });
    scope.querySelectorAll("[data-i18n-placeholder]").forEach(function (el) {
      el.setAttribute("placeholder", window.t(el.getAttribute("data-i18n-placeholder")));
    });
  };

  window.setLang = function (lang) {
    window.I18N_LANG = window.I18N[lang] ? lang : "ru";
    try { localStorage.setItem("obs_lang", window.I18N_LANG); } catch (_) {}
    document.documentElement.lang = window.I18N_LANG;
    window.applyI18n(document);
    return window.I18N_LANG;
  };

  window.initLang = function (fallback) {
    let saved = null;
    try { saved = localStorage.getItem("obs_lang"); } catch (_) {}
    return window.setLang(saved || fallback || "ru");
  };
